    // MARK: - 5. Tailwind CSS Exporter
    private static func exportTailwind(project: DesignSystemProject) -> String {
        var colorsJS = "      colors: {\n"
        for token in project.tokens.filter({ $0.type == .color }) {
            guard let val = token.colorValue else { continue }
            let keyName = token.name.replacingOccurrences(of: ".", with: "-").lowercased()
            colorsJS += "        '\(keyName)': '\(val.lightHex)',\n"
        }
        colorsJS += "      },"
        
        var spacingJS = "      spacing: {\n"
        for token in project.tokens.filter({ $0.type == .spacing }) {
            guard let val = token.spacingValue else { continue }
            let keyName = token.name.replacingOccurrences(of: ".", with: "-").lowercased()
            spacingJS += "        '\(keyName)': '\(val.value)\(val.unit)',\n"
        }
        spacingJS += "      },"
        
        var radiusJS = "      borderRadius: {\n"
        for token in project.tokens.filter({ $0.type == .radius }) {
            guard let val = token.radiusValue else { continue }
            let keyName = token.name.replacingOccurrences(of: ".", with: "-").lowercased()
            radiusJS += "        '\(keyName)': '\(val.value)px',\n"
        }
        radiusJS += "      },"
        
        var fontFamilyJS = "      fontFamily: {\n"
        var fontSizeJS = "      fontSize: {\n"
        for token in project.tokens.filter({ $0.type == .typography }) {
            guard let val = token.typographyValue else { continue }
            let keyName = token.name.replacingOccurrences(of: ".", with: "-").lowercased()
            fontFamilyJS += "        '\(keyName)': ['\(val.fontFamily)', 'sans-serif'],\n"
            fontSizeJS += "        '\(keyName)': ['\(Int(val.fontSize))px', { lineHeight: '\(Int(val.lineHeight))px' }],\n"
        }
        fontFamilyJS += "      },"
        fontSizeJS += "      },"
        
        var boxShadowJS = "      boxShadow: {\n"
        for token in project.tokens.filter({ $0.type == .shadow }) {

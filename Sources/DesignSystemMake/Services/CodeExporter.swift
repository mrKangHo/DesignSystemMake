    // MARK: - Helpers
    private static func fontStyleWeightSwiftUI(_ weight: String) -> String {
        switch weight.lowercased() {
        case "bold": return ".bold"
        case "semibold": return ".semibold"
        case "medium": return ".medium"
        default: return ".regular"
        }
    }
    
    private static func fontWeightCssNumber(_ weight: String) -> String {
        switch weight.lowercased() {
        case "bold": return "700"
        case "semibold": return "600"
        case "medium": return "500"
        default: return "400"
        }
    }
    
    private static func fontWeightKotlinCompose(_ weight: String) -> String {
        switch weight.lowercased() {
        case "bold": return "FontWeight.Bold"
        case "semibold": return "FontWeight.SemiBold"
        case "medium": return "FontWeight.Medium"
        default: return "FontWeight.Normal"
        }
    }
    
    private static func fontWeightFlutterDart(_ weight: String) -> String {
        switch weight.lowercased() {
        case "bold": return "FontWeight.bold"
        case "semibold": return "FontWeight.w600"
        case "medium": return "FontWeight.w500"
        default: return "FontWeight.normal"
        }
    }
    
    private static func sanitizeIdentifier(_ name: String) -> String {
        let parts = name.components(separatedBy: CharacterSet.alphanumerics.inverted)
        let camel = parts.enumerated().map { index, part in
            index == 0 ? part.lowercased() : part.capitalized
        }.joined()
        return camel.isEmpty ? "token" : camel
    }
    
    private static func setValue(in dict: inout [String: Any], keyPath: [String], value: [String: Any]) {
        guard let first = keyPath.first else { return }
        if keyPath.count == 1 {
            dict[first] = value
        } else {
            var sub = (dict[first] as? [String: Any]) ?? [:]
            setValue(in: &sub, keyPath: Array(keyPath.dropFirst()), value: value)
            dict[first] = sub
        }
    }

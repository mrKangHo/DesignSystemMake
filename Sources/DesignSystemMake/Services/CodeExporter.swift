            }
        }

        // MARK: - 5. Shadow Tokens
        public struct ShadowToken {
            public let color: Color
            public let radius: CGFloat
            public let x: CGFloat
            public let y: CGFloat
        }

        public extension ShadowToken {
            struct DesignTokens {
        """
        
        let shadowTokens = project.tokens.filter { $0.type == .shadow }
        for token in shadowTokens {
            guard let val = token.shadowValue else { continue }
            let varName = sanitizeIdentifier(token.name)
            code += """

                /// \(token.displayName) (blur: \(Int(val.blur))px, y: \(Int(val.y))px)
                public static let \(varName) = ShadowToken(
                    color: Color(hex: "\(val.colorHex)").opacity(\(val.opacity)),
                    radius: \(val.blur),
                    x: \(val.x),
                    y: \(val.y)
                )
        """
        }
        
        code += """

            }
        }

        public extension View {
            func shadowToken(_ shadow: ShadowToken) -> some View {
                self.shadow(color: shadow.color, radius: shadow.radius, x: shadow.x, y: shadow.y)
            }
        }

        // MARK: - Helper Extension
        private extension UIColor {
            convenience init?(hex: String) {
                var cleanHex = hex.trimmingCharacters(in: CharacterSet.alphanumerics.inverted)
                if cleanHex.hasPrefix("#") { cleanHex.removeFirst() }
                var int: UInt64 = 0
                guard Scanner(string: cleanHex).scanHexInt64(&int) else { return nil }
                let r, g, b: CGFloat
                switch cleanHex.count {
                case 6:
                    r = CGFloat((int >> 16) & 0xFF) / 255.0
                    g = CGFloat((int >> 8) & 0xFF) / 255.0
                    b = CGFloat(int & 0xFF) / 255.0
                default:
                    return nil
                }
                self.init(red: r, green: g, blue: b, alpha: 1.0)
            }
        }
        """
        
        return code
    }
    

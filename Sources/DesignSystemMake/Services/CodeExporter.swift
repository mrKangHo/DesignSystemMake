            let weightSwiftUI = fontStyleWeightSwiftUI(val.fontWeight)
            code += """

                /// \(token.displayName) (\(val.fontFamily) \(Int(val.fontSize))pt \(val.fontWeight))
                public static let \(varName) = Font.custom("\(val.fontFamily)", size: \(val.fontSize)).weight(\(weightSwiftUI))

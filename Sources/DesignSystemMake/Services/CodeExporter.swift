            let varName = sanitizeIdentifier(token.name)
            code += """

                /// \(token.displayName)
                public static var \(varName): UIFont {
                    UIFont(name: "\(val.fontFamily)", size: \(val.fontSize)) ?? UIFont.systemFont(ofSize: \(val.fontSize))
                }
        """
        }
        
        code += """

            }
        }

        // MARK: - 3. Spacing Tokens
        public extension CGFloat {
            struct DesignTokens {

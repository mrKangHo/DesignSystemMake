import Foundation

public enum ExportTarget: String, CaseIterable, Identifiable {
    case swiftUI_iOS = "SwiftUI (iOS - UIKit & SwiftUI)"
    case pureUIKit_iOS = "UIKit (iOS Native - UIColor, UIFont, CALayer)"
    case swiftUI_macOS = "SwiftUI (macOS - AppKit & SwiftUI)"
    case pureAppKit_macOS = "AppKit (macOS Native - NSColor, NSFont, CALayer)"
    case tailwind = "Tailwind CSS"
    case cssVariables = "CSS Variables"
    case jetpackCompose = "Jetpack Compose (Android)"
    case flutter = "Flutter (Dart)"
    case figmaTokensStudio = "Figma Tokens Studio (JSON)"
    case figmaVariablesPlugin = "Figma Variables Script (JS)"
    case aiAgentMarkdown = "AI Agent Prompt Doc (Claude Code / Antigravity / Codex .md)"
    case w3cJson = "W3C JSON (DTCG)"
    
    public var id: String { rawValue }
    
    public var fileExtension: String {
        switch self {
        case .swiftUI_iOS, .swiftUI_macOS, .pureUIKit_iOS, .pureAppKit_macOS: return "swift"
        case .tailwind: return "js"
        case .cssVariables: return "css"
        case .jetpackCompose: return "kt"
        case .flutter: return "dart"
        case .figmaTokensStudio: return "json"
        case .figmaVariablesPlugin: return "js"
        case .aiAgentMarkdown: return "md"
        case .w3cJson: return "json"
        }
    }
}

public class CodeExporter {
    
    public static func export(project: DesignSystemProject, target: ExportTarget) -> String {
        switch target {
        case .swiftUI_iOS:
            return exportSwiftUI_iOS(project: project)
        case .pureUIKit_iOS:
            return exportPureUIKit_iOS(project: project)
        case .swiftUI_macOS:
            return exportSwiftUI_macOS(project: project)
        case .pureAppKit_macOS:
            return exportPureAppKit_macOS(project: project)
        case .tailwind:
            return exportTailwind(project: project)
        case .cssVariables:
            return exportCSSVariables(project: project)
        case .jetpackCompose:
            return exportJetpackCompose(project: project)
        case .flutter:
            return exportFlutter(project: project)
        case .figmaTokensStudio:
            return exportFigmaTokensStudio(project: project)
        case .figmaVariablesPlugin:
            return exportFigmaVariablesScript(project: project)
        case .aiAgentMarkdown:
            return exportAIAgentMarkdown(project: project)
        case .w3cJson:
            return exportW3CJson(project: project)
        }
    }
    
    // MARK: - 1. iOS SwiftUI & UIKit Exporter
    private static func exportSwiftUI_iOS(project: DesignSystemProject) -> String {
        var code = """
        // Generated by DesignSystemMake v\(project.version) for iOS
        // Target Framework: UIKit + SwiftUI (iOS 15.0+)
        // Complete Token Set: Colors, Typography, Spacing, Border Radius, Shadows
        // Date: \(DateFormatter.localizedString(from: Date(), dateStyle: .medium, timeStyle: .none))

        import SwiftUI
        import UIKit

        // MARK: - 1. Color Tokens (UIKit & SwiftUI)
        public extension UIColor {
            struct DesignTokens {
        """
        
        let colorTokens = project.tokens.filter { $0.type == .color }
        for token in colorTokens {
            guard let val = token.colorValue else { continue }
            let varName = sanitizeIdentifier(token.name)
            if let darkHex = val.darkHex, darkHex != val.lightHex {
                code += """

                /// \(token.displayName): \(token.description)
                public static var \(varName): UIColor {
                    UIColor { traitCollection in
                        if traitCollection.userInterfaceStyle == .dark {
                            return UIColor(hex: "\(darkHex)") ?? .systemBlue
                        } else {
                            return UIColor(hex: "\(val.lightHex)") ?? .systemBlue
                        }
                    }
                }
        """
            } else {
                code += """

                /// \(token.displayName): \(token.description)
                public static let \(varName) = UIColor(hex: "\(val.lightHex)") ?? .systemBlue
        """
            }
        }
        
        code += """

            }
        }

        public extension Color {
            struct DesignTokens {
        """
        
        for token in colorTokens {
            let varName = sanitizeIdentifier(token.name)
            code += """

                /// \(token.displayName)
                public static var \(varName): Color { Color(uiColor: UIColor.DesignTokens.\(varName)) }
        """
        }
        
        code += """

            }
        }

        // MARK: - 2. Typography Tokens (Font & SwiftUI TextStyle)
        public extension Font {
            struct DesignTokens {
        """
        
        let typographyTokens = project.tokens.filter { $0.type == .typography }
        for token in typographyTokens {
            guard let val = token.typographyValue else { continue }
